#!/usr/bin/env bash
# Prepare a fresh checkout for the native (no Docker) Penpot stack.
#
#   scripts/native/setup.sh              # full setup
#   scripts/native/setup.sh --skip-wasm  # skip the Rust/WASM build
#
# System packages (Postgres, Valkey/Redis, nginx, JDK 23+, Node 20+, pnpm,
# Clojure CLI) must already be installed; the script checks them and prints
# install hints. Everything user-level (Emscripten, Rust target, node_modules,
# database cluster, generated configs) is created here.
#
# Safe to re-run: existing data, configs and build artifacts are reused.

set -euo pipefail

SKIP_WASM=${PENPOT_NATIVE_SKIP_WASM:-0}
for arg in "$@"; do
    case "$arg" in
        --skip-wasm) SKIP_WASM=1 ;;
        -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
        *) echo "unknown option: $arg" >&2; exit 2 ;;
    esac
done

. "$(dirname "$0")/common.sh"

info() { printf '%-14s %s\n' "$1" "$2"; }
fail() { echo "error: $*" >&2; exit 1; }

# ---------------------------------------------------------------- prerequisites

missing=()
need() { have "$1" || missing+=("$1"); }
need git; need curl; need psql; need initdb; need pg_ctl; need pg_isready
need redis-server; need redis-cli; need nginx; need node; need pnpm
need clojure
if ! have java && ! { [ -n "${JAVA_HOME:-}" ] && [ -x "$JAVA_HOME/bin/java" ]; }; then
    missing+=(java)
fi

if [ ${#missing[@]} -gt 0 ]; then
    {
        echo "Missing required commands: ${missing[*]}"
        echo
        echo "Install hints (Debian/Ubuntu):"
        echo "  sudo apt install postgresql redis-server nginx curl git"
        echo "  JDK 23+:        https://adoptium.net (default-jdk may be older)"
        echo "  Node 20+ + pnpm: https://nodejs.org / corepack enable pnpm"
        echo "  Clojure CLI:    https://clojure.org/guides/install_clojure"
        echo "  Or install all user-level tools at once: mise install"
        echo "  (versions in mise.toml; see scripts/native/README.md)"
    } >&2
    exit 1
fi

node_major=$(node -e 'process.stdout.write(process.versions.node.split(".")[0])')
if [ "$node_major" -lt 20 ]; then
    fail "Node 20+ required (found $(node --version))"
fi
NODE_BIN=$(dirname "$(command -v node)")

# Prefer a JDK 27 (the version the Docker devenv pins). Any JDK 23+ works; the
# generated _env.local drops the flags older JVMs reject.
pick_java_home() {
    local best="" best_major=0 home major
    local candidates=()
    [ -n "${PENPOT_JAVA_HOME:-}" ] && candidates+=("$PENPOT_JAVA_HOME")
    [ -n "${JAVA_HOME:-}" ] && candidates+=("$JAVA_HOME")
    for home in /usr/lib/jvm/* "$HOME"/.local/share/mise/installs/java/* \
                "${MISE_DATA_DIR:-$HOME/.local/share/mise}/installs/java"/*; do
        [ -x "$home/bin/java" ] && candidates+=("$home")
    done
    if have java; then
        candidates+=("")
    fi
    for home in "${candidates[@]}"; do
        major=$(java_major "$home") || continue
        [ -n "$major" ] || continue
        if [ "$major" -ge 27 ]; then
            echo "$home"
            return
        fi
        if [ "$major" -ge 23 ] && [ "$major" -gt "$best_major" ]; then
            best=$home
            best_major=$major
        fi
    done
    echo "$best"
}

JAVA_HOME_LOCAL=$(pick_java_home)
[ -n "$JAVA_HOME_LOCAL" ] || fail "JDK 23+ required (not found)"
JAVA_MAJOR=$(java_major "$JAVA_HOME_LOCAL")
if [ "$JAVA_MAJOR" -lt 23 ]; then
    fail "JDK 23+ required (found $JAVA_MAJOR)"
fi
info java "$JAVA_HOME_LOCAL ($JAVA_MAJOR)"

# Emscripten is only needed for the WASM renderer; install the pinned version
# on demand (user-local, no root required).
EMSDK=${EMSDK:-$HOME/emsdk}
WASM_OUT="$REPO/frontend/resources/public/js/render-wasm.wasm"
if [ "$SKIP_WASM" = 0 ] && [ ! -f "$WASM_OUT" ]; then
    if [ ! -f "$EMSDK/emsdk_env.sh" ]; then
        echo "emscripten: installing 4.0.6 into $EMSDK (this takes a few minutes)"
        git clone --depth 1 https://github.com/emscripten-core/emsdk.git "$EMSDK"
        (cd "$EMSDK" && ./emsdk install 4.0.6 && ./emsdk activate 4.0.6)
    fi
    if have rustup; then
        rustup target add wasm32-unknown-emscripten >/dev/null 2>&1 || true
    fi
fi

# ------------------------------------------------------------ machine settings

cat > "$RUNTIME_ENV" <<EOF
# Generated by scripts/native/setup.sh. Machine-specific; do not commit.
JAVA_HOME=$JAVA_HOME_LOCAL
NODE_BIN=$NODE_BIN
EMSDK=$EMSDK
EOF
info config "$RUNTIME_ENV"

# --------------------------------------------------------------- local configs

mkdir -p "$REPO/frontend/resources/public/js" "$REPO/backend/assets"

ENV_LOCAL="$REPO/backend/scripts/_env.local"
if [ -f "$ENV_LOCAL" ]; then
    info config "_env.local exists (kept)"
else
    cat > "$ENV_LOCAL" <<EOF
#!/usr/bin/env bash
# Generated by scripts/native/setup.sh. Gitignored.
# Local overrides for backend/scripts/_env (native PostgreSQL + Valkey).

export PENPOT_HOST=localhost
export PENPOT_PUBLIC_URI=$PUBLIC_URI

export PENPOT_DATABASE_URI=postgresql://$PG_HOST:$PG_PORT/$PG_DB
export PENPOT_DATABASE_USERNAME=$PG_USER
export PENPOT_DATABASE_PASSWORD=$PG_PASSWORD
export PENPOT_DATABASE_MAX_POOL_SIZE=20
export PENPOT_REDIS_URI=redis://$PG_HOST:$VALKEY_PORT/0

# Filesystem object storage; no S3/RustFS needed.
export PENPOT_OBJECTS_STORAGE_BACKEND=fs
export PENPOT_OBJECTS_STORAGE_FS_DIRECTORY=assets

# No local SMTP or LDAP server.
export PENPOT_FLAGS="\$PENPOT_FLAGS disable-smtp disable-login-with-ldap"
EOF
    if [ "$JAVA_MAJOR" -lt 27 ]; then
        cat >> "$ENV_LOCAL" <<'EOF'

# JDK < 27 rejects some of these flags; the defaults below also work on JDK 27.
export JAVA_OPTS="${JAVA_OPTS//-XX:+UseCompactObjectHeaders/}"
export JAVA_OPTS="${JAVA_OPTS//--sun-misc-unsafe-memory-access=allow/}"
export JAVA_OPTS="${JAVA_OPTS//-XX:+UseShenandoahGC/}"
export JAVA_OPTS="${JAVA_OPTS//-XX:ShenandoahGCMode=generational/}"
EOF
    fi
    info config "_env.local created"
fi

CONFIG_JS="$REPO/frontend/resources/public/js/config.js"
if [ ! -f "$CONFIG_JS" ]; then
    cat > "$CONFIG_JS" <<'EOF'
// Generated by scripts/native/setup.sh. Gitignored.
var penpotFlags = "enable-login-with-password disable-login-with-oidc disable-login-with-google disable-login-with-github disable-login-with-gitlab enable-demo-users enable-access-tokens disable-telemetry";
EOF
    info config "config.js created"
else
    info config "config.js exists (kept)"
fi

# ------------------------------------------------------------------- database

if [ ! -s "$PGDATA/PG_VERSION" ]; then
    info postgres "creating cluster at $PGDATA"
    initdb -D "$PGDATA" -A trust -U "$(id -un)" --encoding=UTF8 >/dev/null
fi

# Refuse to provision a database on top of a foreign PostgreSQL instance.
if ! pg_ctl -D "$PGDATA" status >/dev/null 2>&1 \
   && pg_isready -h "$PG_HOST" -p "$PG_PORT" -q 2>/dev/null; then
    fail "another PostgreSQL server is using port $PG_PORT; set PENPOT_PG_PORT to a free port and delete $REPO/backend/scripts/_env.local to regenerate it"
fi

PG_OPTS="-p $PG_PORT -k ${TMPDIR:-/tmp} -c listen_addresses=127.0.0.1 -c max_connections=160 -c shared_buffers=256MB"
PG_SOCKET_DIR=${TMPDIR:-/tmp}
if pg_isready -h "$PG_HOST" -p "$PG_PORT" -q 2>/dev/null; then
    info postgres "already running"
else
    info postgres "starting"
    pg_ctl -D "$PGDATA" -l "$LOG_DIR/postgres.log" -o "$PG_OPTS" start >/dev/null
fi

# Administration uses the local socket and the OS user (trust auth); the
# application connects over TCP as the unprivileged penpot role.
psql_super() { psql -w -h "$PG_SOCKET_DIR" -p "$PG_PORT" -U "$(id -un)" -d postgres -tAc "$1"; }

if [ "$(psql_super "SELECT 1 FROM pg_roles WHERE rolname='$PG_USER'")" != "1" ]; then
    psql_super "CREATE ROLE $PG_USER LOGIN PASSWORD '$PG_PASSWORD'" >/dev/null
    info postgres "role $PG_USER created"
fi
for db in "$PG_DB" "$PG_TEST_DB"; do
    if [ "$(psql_super "SELECT 1 FROM pg_database WHERE datname='$db'")" != "1" ]; then
        psql_super "CREATE DATABASE $db OWNER $PG_USER" >/dev/null
        info postgres "database $db created"
    fi
    psql -w -h "$PG_SOCKET_DIR" -p "$PG_PORT" -U "$(id -un)" -d "$db" \
        -c 'CREATE EXTENSION IF NOT EXISTS "uuid-ossp"' >/dev/null
done
info postgres "ready on $PG_HOST:$PG_PORT"

# ---------------------------------------------------------------------- nginx

render_nginx_conf
info nginx "config at $NGINX_DIR/nginx.conf"

# ------------------------------------------------------------------- frontend

if [ ! -d "$REPO/frontend/node_modules" ]; then
    info frontend "installing dependencies (pnpm install)"
    (cd "$REPO/frontend" && pnpm install)
fi
if [ ! -f "$REPO/frontend/resources/public/index.html" ]; then
    info frontend "building static assets"
    (cd "$REPO/frontend" && pnpm run build:app:assets)
fi

# ---------------------------------------------------------------------- wasm

if [ "$SKIP_WASM" = 1 ]; then
    info wasm "skipped (--skip-wasm)"
elif [ -f "$WASM_OUT" ]; then
    info wasm "already built"
else
    info wasm "building (slow on first run)"
    EMSDK="$EMSDK" "$REPO/scripts/native/build-render-wasm.sh"
fi

echo
echo "Setup complete. Start the stack with:  just up"
